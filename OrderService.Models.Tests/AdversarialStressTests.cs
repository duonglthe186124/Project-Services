    [Fact]
    public async Task Decimal_Serialization_Type_And_Precision_In_MongoDB()
    {
        var orders = _database.GetCollection<Order>(OrderDbInitializer.OrdersCollectionName);
        var rawCollection = _database.GetCollection<BsonDocument>(OrderDbInitializer.OrdersCollectionName);

        var testCode = "ADI-DECIMAL-" + Guid.NewGuid().ToString()[..8];
        var order = new Order
        {
            OrderCode = testCode,
            UserId = "user_decimal",
            SubTotal = 15500000.50m,
            ShippingFee = 35000m,
            DiscountAmount = 500000m,
            TotalAmount = 15035000.50m,
            Items = new List<OrderItem>
            {
                new()
                {
                    ProductId = "prod_dec",
                    UnitPrice = 15500000.50m,
                    LineTotal = 15500000.50m,
                    Quantity = 1,
                    Size = 42
                }
            }
        };

        await orders.InsertOneAsync(order);

        // Read back as raw BSON to inspect underlying BSON types
        var filter = Builders<BsonDocument>.Filter.Eq("orderCode", testCode);
        var rawDoc = await rawCollection.Find(filter).FirstOrDefaultAsync();

        Assert.NotNull(rawDoc);
        Assert.Equal(BsonType.Decimal128, rawDoc["totalAmount"].BsonType);
        Assert.Equal(BsonType.Decimal128, rawDoc["subTotal"].BsonType);
        Assert.Equal(BsonType.Decimal128, rawDoc["shippingFee"].BsonType);
        Assert.Equal(BsonType.Decimal128, rawDoc["discountAmount"].BsonType);

        var rawItem = rawDoc["items"].AsBsonArray[0].AsBsonDocument;
        Assert.Equal(BsonType.Decimal128, rawItem["unitPrice"].BsonType);
        Assert.Equal(BsonType.Decimal128, rawItem["lineTotal"].BsonType);

        // Verify decimal precision preserved
        Assert.Equal(15035000.50m, rawDoc["totalAmount"].AsDecimal);
    }

    [Fact]
    public async Task ExistingIndex_Conflict_Analysis_Documented()
    {
        // Test what happens if an existing index on Carts has a DIFFERENT name
        var testColName = "TestCol_Conflict_" + Guid.NewGuid().ToString()[..6];
        var col = _database.GetCollection<BsonDocument>(testColName);

        // Create an index with default name "userId_1"
        await col.Indexes.CreateOneAsync(new CreateIndexModel<BsonDocument>(
            Builders<BsonDocument>.IndexKeys.Ascending("userId")
        ));

        // Now attempt to create "ux_userId" with unique: true on the same key
        var conflictModel = new CreateIndexModel<BsonDocument>(
            Builders<BsonDocument>.IndexKeys.Ascending("userId"),
            new CreateIndexOptions { Name = "ux_userId", Unique = true }
        );

        var ex = await Record.ExceptionAsync(() => col.Indexes.CreateOneAsync(conflictModel));
        var indexes = (await col.Indexes.ListAsync()).ToList();
        
        // Assert how MongoDB handles existing index with same key but different name
        // In MongoDB Atlas (modern version), does it accept or ignore or throw?
        Assert.Null(ex); // MongoDB did NOT throw!
        Assert.Contains(indexes, idx => idx["name"] == "ux_userId");

        // Cleanup
        await _database.DropCollectionAsync(testColName);
    }
