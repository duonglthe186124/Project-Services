    [Fact]
    public async Task OCC_Concurrent_Transitions_Only_One_Succeeds()
    {
        await OrderDbInitializer.InitializeAsync(_database);
        var sagas = _database.GetCollection<OrderSagaState>(OrderDbInitializer.OrderSagaStatesCollectionName);

        var orderId = "occ_order_" + Guid.NewGuid();
        var initialSaga = new OrderSagaState
        {
            OrderId = orderId,
            OrderCode = "ADI-OCC-TEST",
            UserId = "user_occ",
            CurrentState = OrderStatusConstants.AwaitingPayment,
            Version = 1,
            ExpiresAt = DateTime.UtcNow.AddMinutes(15)
        };
        await sagas.InsertOneAsync(initialSaga);

        // Simulate two racing threads attempting state transition
        var filter1 = Builders<OrderSagaState>.Filter.And(
            Builders<OrderSagaState>.Filter.Eq(s => s.OrderId, orderId),
            Builders<OrderSagaState>.Filter.Eq(s => s.Version, 1),
            Builders<OrderSagaState>.Filter.Eq(s => s.CurrentState, OrderStatusConstants.AwaitingPayment)
        );
        var update1 = Builders<OrderSagaState>.Update
            .Set(s => s.CurrentState, OrderStatusConstants.PaymentVerified)
            .Inc(s => s.Version, 1)
            .Set(s => s.UpdatedAt, DateTime.UtcNow);

        var filter2 = Builders<OrderSagaState>.Filter.And(
            Builders<OrderSagaState>.Filter.Eq(s => s.OrderId, orderId),
            Builders<OrderSagaState>.Filter.Eq(s => s.Version, 1),
            Builders<OrderSagaState>.Filter.Eq(s => s.CurrentState, OrderStatusConstants.AwaitingPayment)
        );
        var update2 = Builders<OrderSagaState>.Update
            .Set(s => s.CurrentState, OrderStatusConstants.Cancelled)
            .Inc(s => s.Version, 1)
            .Set(s => s.UpdatedAt, DateTime.UtcNow);

        // Execute concurrently
        var task1 = sagas.FindOneAndUpdateAsync(filter1, update1);
        var task2 = sagas.FindOneAndUpdateAsync(filter2, update2);

        var results = await Task.WhenAll(task1, task2);

        // Assert: Exactly one won the race, the other got null (conflict)
        var winnerCount = results.Count(r => r != null);
        var loserCount = results.Count(r => r == null);

        Assert.Equal(1, winnerCount);
        Assert.Equal(1, loserCount);

        // Verify database state: Version is 2, not 3
        var finalSaga = await sagas.Find(s => s.OrderId == orderId).FirstOrDefaultAsync();
        Assert.NotNull(finalSaga);
        Assert.Equal(2, finalSaga.Version);
        Assert.True(finalSaga.CurrentState == OrderStatusConstants.PaymentVerified || finalSaga.CurrentState == OrderStatusConstants.Cancelled);
    }

